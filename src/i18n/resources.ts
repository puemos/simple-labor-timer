type PartialDeep<T> = {
  [K in keyof T]?: T[K] extends object ? PartialDeep<T[K]> : T[K];
};

function mergeDeep<T extends Record<string, unknown>>(base: T, override: PartialDeep<T>): T {
  const result: Record<string, unknown> = { ...base };
  Object.entries(override).forEach(([key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      result[key] = mergeDeep((base[key] ?? {}) as Record<string, unknown>, value as PartialDeep<Record<string, unknown>>);
      return;
    }
    if (value !== undefined) {
      result[key] = value;
    }
  });
  return result as T;
}
